def print_matrix(name, state_array):
    """Вывод 16-байтного массива в виде матрицы 4x4 (заполнение по столбцам)"""
    print(f"\n{name}:")
    for r in range(4):
        row = [f"{state_array[r + 4 * c]:02X}" for c in range(4)]
        print("  " + " ".join(row))


# --- 1. Инициализация ---
