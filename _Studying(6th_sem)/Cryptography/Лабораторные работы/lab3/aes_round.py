# Генерация случайного State (16 байт) и раундового ключа
state = [random.randint(0, 255) for _ in range(16)]
round_key = [random.randint(0, 255) for _ in range(16)]

print_matrix("Входная матрица State (заполнение по столбцам)", state)
print_matrix("Раундовый ключ K_i", round_key)


# --- 2. AddRoundKey ---
# Побитовое сложение по модулю 2 (XOR) состояния и ключа
