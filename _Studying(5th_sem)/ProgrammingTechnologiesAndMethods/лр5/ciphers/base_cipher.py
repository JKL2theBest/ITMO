# -*- coding: utf-8 -*-

"""
(Опциональный) Модуль с базовым абстрактным классом для шифров.

Использование такого класса позволило бы унифицировать все шифры
под единым интерфейсом, что полезно в более крупных системах.
Для данной лабораторной работы это избыточно, но является примером
хорошего архитектурного задела на будущее.
"""

from abc import ABC, abstractmethod

class BaseCipher(ABC):
    """Абстрактный базовый класс для всех алгоритмов шифрования."""

    @abstractmethod
    def encrypt(self, text: str, key) -> str:
        """Метод для шифрования текста."""
        pass

    @abstractmethod
    def decrypt(self, ciphertext: str, key) -> str:
        """Метод для дешифрования текста."""
        pass