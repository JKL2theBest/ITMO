"""
Модуль конфигурации приложения.

Определяет и предоставляет доступ к основным параметрам системы, таким как
настройки базы данных и параметры безопасности. Использование класса на базе
Pydantic обеспечивает валидацию типов и значений при запуске.
"""

from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    """
    Класс для управления конфигурацией приложения.
    """

    # --- Настройки базы данных ---
    # Путь к файлу базы данных SQLite.
    DATABASE_URL: str = "sqlite+aiosqlite:///./auth_system.db"

    # --- Параметры безопасности ---
    # Схема хеширования паролей. Argon2id является рекомендованным стандартом.
    PASSWORD_HASH_SCHEME: str = "argon2"

    # Параметры Argon2id, определяющие криптостойкость хеша.
    # Рекомендованные значения OWASP на 2024 год.
    ARGON2_TIME_COST: int = 3  # Количество итераций
    ARGON2_MEMORY_COST: int = 65536  # Объем памяти в кибибайтах (64 МБ)
    ARGON2_PARALLELISM: int = 4  # Количество параллельных потоков


# Создаем единственный экземпляр настроек для всего приложения.
settings = Settings()
